// Helper to get or initialize localStorage store
export const getLocalStore = (key, initial) => {
  try {
    const item = localStorage.getItem(`rw_${key}`);
    if (item) return JSON.parse(item);
    localStorage.setItem(`rw_${key}`, JSON.stringify(initial));
    return initial;
  } catch (e) {
    return initial;
  }
};

export const setLocalStore = (key, data) => {
  try {
    localStorage.setItem(`rw_${key}`, JSON.stringify(data));
  } catch (e) {
    console.warn('LocalStorage save error:', e);
  }
};
